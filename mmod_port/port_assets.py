"""Install, track and remove assets ported from Half-Life: MMod.

assets.json is the single list of every MMod file this project uses. Nothing is copied unless it is listed
there, so the list (and the ASSETS.md report generated from it) is always the complete set of MMod-derived
files in a mod installation. MMod's files are never committed to this repository.

Commands:
    install  Copy or convert the listed assets from an MMod installation into the mod directory.
    verify   Show the state of each listed asset in the mod directory.
    remove   Delete installed assets that are unchanged since installation.
    add      Add files from the MMod installation to the manifest.
    report   Regenerate ASSETS.md from the manifest.

Run with --help on any command for its options. Requires Python 3.9+, standard library only.
"""

import argparse
import hashlib
import json
import re
import shutil
import sys
from collections import defaultdict
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
MANIFEST_PATH = SCRIPT_DIR / "assets.json"
REPORT_PATH = SCRIPT_DIR / "ASSETS.md"

# Written into the mod directory by install, so remove only touches files this script put there.
INSTALL_RECORD_NAME = "mmod_port_installed.json"

DEFAULT_MMOD_DIR = r"C:\Program Files (x86)\Steam\steamapps\common\Half-Life MMod\HL1MMod"
DEFAULT_MOD_DIR = r"C:\Program Files (x86)\Steam\steamapps\common\Half-Life\johnhalflife"

# Texture names in the SDK's material system can be up to 15 characters.
MAX_TEXTURE_NAME_LENGTH = 15


def sha256_of(path):
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_manifest():
    with open(MANIFEST_PATH, encoding="utf-8") as f:
        return json.load(f)


def save_manifest(manifest):
    manifest["Assets"].sort(key=lambda a: a["Path"].lower())
    with open(MANIFEST_PATH, "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, indent="\t")
        f.write("\n")


def output_path(asset):
    """Path of the file written into the mod directory, relative to it."""
    return asset.get("Output", asset["Path"])


def strip_texture_prefix(name):
    """Remove the prefixes the game ignores when looking up texture names (see MaterialSystem::StripTexturePrefix)."""
    if name[:1] in ("-", "+"):
        name = name[2:]
    if name[:1] in ("{", "!", "~", " "):
        name = name[1:]
    return name


def convert_materials(source, destination):
    """Convert an MMod materials.txt ("<type> <texture>" per line) into the SDK's materials JSON format."""
    materials = {}
    for line_number, raw_line in enumerate(source.read_text(encoding="latin-1").splitlines(), 1):
        line = raw_line.split("//", 1)[0].strip()
        if not line:
            continue

        parts = line.split()
        if len(parts) < 2 or len(parts[0]) != 1:
            print(f"  warning: {source.name}:{line_number}: skipping malformed line: {raw_line!r}")
            continue

        texture_type, texture_name = parts[0].upper(), strip_texture_prefix(parts[1].upper())
        if not re.fullmatch(r"\w+", texture_name):
            # The game rejects the whole file if any name has other characters.
            print(f"  warning: {source.name}:{line_number}: invalid texture name, skipped: {texture_name}")
            continue

        if len(texture_name) > MAX_TEXTURE_NAME_LENGTH:
            print(f"  warning: {source.name}:{line_number}: texture name too long, skipped: {texture_name}")
            continue

        # Later entries win, matching how the game merges materials files.
        materials[texture_name] = texture_type

    lines = [
        "// Generated by mmod_port/port_assets.py from Half-Life: MMod's sound/materials.txt. Do not edit.",
        "// Loaded after sound/materials.json, so these assignments take precedence.",
        "{",
    ]
    entries = [f'\t"{name}": {{\n\t\t"Type": "{texture_type}"\n\t}}' for name, texture_type in sorted(materials.items())]
    lines.append(",\n".join(entries))
    lines.append("}")

    destination.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"  converted {len(materials)} material assignments")


ACTIONS = {
    "copy": lambda source, destination: shutil.copyfile(source, destination),
    "convert-materials": convert_materials,
}


def load_install_record(mod_dir):
    path = mod_dir / INSTALL_RECORD_NAME
    if path.exists():
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    return {}


def save_install_record(mod_dir, record):
    path = mod_dir / INSTALL_RECORD_NAME
    if record:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            json.dump(record, f, indent="\t", sort_keys=True)
            f.write("\n")
    elif path.exists():
        path.unlink()


def command_install(args):
    manifest = load_manifest()
    mmod_dir, mod_dir = Path(args.mmod_dir), Path(args.mod_dir)
    record = load_install_record(mod_dir)
    failures = 0

    for asset in manifest["Assets"]:
        if args.feature and asset["Feature"] not in args.feature:
            continue

        source = mmod_dir / asset["Path"]
        relative_output = output_path(asset)
        destination = mod_dir / relative_output

        if not source.is_file():
            print(f"MISSING  {asset['Path']}: not found in the MMod installation")
            failures += 1
            continue

        if sha256_of(source) != asset["Sha256"]:
            print(f"CHANGED  {asset['Path']}: differs from the version recorded in assets.json "
                  "(MMod may have been updated); re-run 'add' for it if the new version is wanted")
            failures += 1
            continue

        # Never overwrite a file this script did not install, or one changed since it was installed.
        if destination.exists():
            installed_hash = record.get(relative_output)
            if installed_hash is None or installed_hash != sha256_of(destination):
                if not args.force:
                    print(f"SKIPPED  {relative_output}: already exists in the mod directory and was not installed "
                          "by this script (use --force to overwrite)")
                    failures += 1
                    continue

        destination.parent.mkdir(parents=True, exist_ok=True)
        print(f"{asset['Action'].upper():8} {asset['Path']} -> {relative_output}")
        ACTIONS[asset["Action"]](source, destination)
        record[relative_output] = sha256_of(destination)

    save_install_record(mod_dir, record)
    print(f"\n{len(record)} MMod-derived files installed in {mod_dir}")
    return 1 if failures else 0


def command_verify(args):
    manifest = load_manifest()
    mod_dir = Path(args.mod_dir)
    record = load_install_record(mod_dir)
    problems = 0

    for asset in manifest["Assets"]:
        relative_output = output_path(asset)
        destination = mod_dir / relative_output

        if not destination.exists():
            state = "not installed"
            problems += 1
        elif relative_output not in record:
            state = "present, but not installed by this script"
            problems += 1
        elif record[relative_output] != sha256_of(destination):
            state = "modified since installation"
            problems += 1
        else:
            state = "ok"

        print(f"{state:42} {relative_output}")

    return 1 if problems else 0


def command_remove(args):
    mod_dir = Path(args.mod_dir)
    record = load_install_record(mod_dir)

    for relative_output, installed_hash in sorted(record.items()):
        destination = mod_dir / relative_output
        if not destination.exists():
            print(f"gone     {relative_output}")
            del record[relative_output]
        elif sha256_of(destination) == installed_hash or args.force:
            destination.unlink()
            print(f"removed  {relative_output}")
            del record[relative_output]
        else:
            print(f"kept     {relative_output}: modified since installation (use --force to delete anyway)")

    save_install_record(mod_dir, record)
    return 0


def command_add(args):
    manifest = load_manifest()
    mmod_dir = Path(args.mmod_dir)
    known = {asset["Path"].lower(): asset for asset in manifest["Assets"]}

    for path in args.paths:
        relative = Path(path).as_posix()
        source = mmod_dir / relative
        if not source.is_file():
            print(f"error: {relative} not found in {mmod_dir}")
            return 1

        asset = known.get(relative.lower())
        if asset is None:
            asset = {"Path": relative}
            manifest["Assets"].append(asset)
            known[relative.lower()] = asset

        asset["Action"] = args.action
        asset["Feature"] = args.feature
        asset["Sha256"] = sha256_of(source)
        if args.output:
            asset["Output"] = args.output
        if args.notes:
            asset["Notes"] = args.notes
        print(f"recorded {relative}")

    save_manifest(manifest)
    write_report(manifest)
    return 0


def write_report(manifest):
    assets = manifest["Assets"]

    # Group by folder, then by file type.
    groups = defaultdict(lambda: defaultdict(list))
    for asset in assets:
        path = Path(asset["Path"])
        location = path.parent.as_posix() if len(path.parts) > 1 else "(mod root)"
        file_type = path.suffix.lower().lstrip(".") or "(none)"
        groups[location][file_type].append(asset)

    lines = [
        "# MMod-derived assets",
        "",
        "Generated by `port_assets.py report` from `assets.json`. Do not edit by hand.",
        "",
        "Every file from Half-Life: MMod that this project uses is listed here. These files are **not** in this",
        "repository; `port_assets.py install` copies them from a local MMod installation into the mod directory.",
        "Before publishing, each of these must be replaced, removed, or cleared with its author.",
        "",
        f"Source: {manifest['Source']}",
        "",
        f"**{len(assets)} files** in {len(groups)} folder{'s' if len(groups) != 1 else ''}.",
        "",
        "| Location | Type | Files |",
        "|---|---|---|",
    ]
    for location in sorted(groups):
        for file_type in sorted(groups[location]):
            lines.append(f"| `{location}/` | {file_type} | {len(groups[location][file_type])} |")

    for location in sorted(groups):
        lines += ["", f"## `{location}/`"]
        for file_type in sorted(groups[location]):
            lines += ["", f"### {file_type}", "", "| File | Installed as | Used by | Notes |", "|---|---|---|---|"]
            for asset in sorted(groups[location][file_type], key=lambda a: a["Path"].lower()):
                installed_as = "same path" if output_path(asset) == asset["Path"] else f"`{output_path(asset)}` ({asset['Action']})"
                lines.append(f"| `{asset['Path']}` | {installed_as} | {asset['Feature']} | {asset.get('Notes', '')} |")

    REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {REPORT_PATH.name}: {len(assets)} assets")


def command_report(args):
    write_report(load_manifest())
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)

    install = commands.add_parser("install", help="copy or convert listed assets into the mod directory")
    install.add_argument("--mmod-dir", default=DEFAULT_MMOD_DIR, help="MMod's HL1MMod directory")
    install.add_argument("--mod-dir", default=DEFAULT_MOD_DIR, help="this mod's game directory")
    install.add_argument("--feature", action="append", help="only install assets for this feature (repeatable)")
    install.add_argument("--force", action="store_true", help="overwrite files not installed by this script")
    install.set_defaults(func=command_install)

    verify = commands.add_parser("verify", help="show the state of each listed asset in the mod directory")
    verify.add_argument("--mod-dir", default=DEFAULT_MOD_DIR)
    verify.set_defaults(func=command_verify)

    remove = commands.add_parser("remove", help="delete assets installed by this script")
    remove.add_argument("--mod-dir", default=DEFAULT_MOD_DIR)
    remove.add_argument("--force", action="store_true", help="also delete files modified since installation")
    remove.set_defaults(func=command_remove)

    add = commands.add_parser("add", help="record MMod files in the manifest")
    add.add_argument("paths", nargs="+", help="paths relative to the MMod directory, e.g. sound/player/pl_jump1.wav")
    add.add_argument("--feature", required=True, help="feature that uses the files, e.g. movement")
    add.add_argument("--action", default="copy", choices=sorted(ACTIONS))
    add.add_argument("--output", help="installed path, if different from the source path")
    add.add_argument("--notes", help="free-form notes, e.g. what vanilla file it replaces")
    add.add_argument("--mmod-dir", default=DEFAULT_MMOD_DIR)
    add.set_defaults(func=command_add)

    report = commands.add_parser("report", help="regenerate ASSETS.md")
    report.set_defaults(func=command_report)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
